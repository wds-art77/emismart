// Regenerates lib/rules/countries/index.ts from the files present. Run after adding a country rules file.
import { readdirSync, writeFileSync } from "node:fs";
const dir = "lib/rules/countries";
const codes = readdirSync(dir).filter((f) => /^[a-z]{2}\.ts$/.test(f)).map((f) => f.slice(0, 2)).sort();
const imports = codes.map((c) => `import { ${c} as ${c}_ } from "./${c}";`).join("\n");
const regs = codes.map((c) => `registerRules(${c}_);`).join("\n");
writeFileSync(`${dir}/index.ts`, `// Generated by scripts/gen-rules-index.mjs: registers every researched country rules file.\nimport { registerRules } from "../registry";\n${imports}\n\n${regs}\n\nexport const availableRules = [${codes.map((c) => `"${c}"`).join(", ")}] as const;\n`);
console.log("registered", codes.join(" ") || "(none)");
